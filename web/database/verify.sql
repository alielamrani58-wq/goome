-- Run inside a single transaction. All test identities and records roll back.
begin;
do $$
declare
 passenger uuid:=gen_random_uuid(); driver_a uuid:=gen_random_uuid(); driver_b uuid:=gen_random_uuid(); admin_id uuid:=gen_random_uuid();
 item record; q text; signature text; signing_key text; ride_id uuid; result jsonb; denied boolean; current_version integer;
begin
 for item in select * from (values(passenger,'passenger'),(driver_a,'driver'),(driver_b,'driver'),(admin_id,'admin')) v(id,kind) loop
   insert into auth.users(id,aud,role,email,email_confirmed_at,created_at,updated_at,raw_app_meta_data,raw_user_meta_data)
   values(item.id,'authenticated','authenticated',item.id::text||'@goome.invalid',now(),now(),now(),'{}','{}');
   if item.kind='admin' then insert into goome_private.admin_emails(email) values(item.id::text||'@goome.invalid'); end if;
   perform set_config('request.jwt.claim.sub',item.id::text,true);
   perform public.goome_register('Test '||item.kind,case when item.kind='admin' then 'passenger' else item.kind end,'+33600000000');
 end loop;
 perform set_config('request.jwt.claim.sub',driver_a::text,true);
 denied:=false; begin perform public.goome_register('Intruder','admin',''); exception when others then denied:=true; end;
 if not denied then raise exception 'FAILED: role escalation'; end if;
 perform public.goome_vehicle('Test Vehicle','TEST-A','Noir','standard');
 perform public.goome_location(48.8566,2.3522,10);
 denied:=false; begin perform public.goome_online(true); exception when others then denied:=true; end;
 if not denied then raise exception 'FAILED: unapproved driver went online'; end if;
 perform set_config('request.jwt.claim.sub',driver_b::text,true);
 perform public.goome_vehicle('Other Vehicle','TEST-B','Blanc','standard');
 perform public.goome_location(48.8567,2.3523,10);
 perform set_config('request.jwt.claim.sub',admin_id::text,true);
 perform public.goome_admin_driver(driver_a,true); perform public.goome_admin_driver(driver_b,true);
 result:=public.goome_snapshot();
 if result->'profile'->>'role'<>'admin' or jsonb_array_length(result->'drivers')<>2 then raise exception 'FAILED: admin snapshot'; end if;
 perform set_config('request.jwt.claim.sub',driver_a::text,true); perform public.goome_online(true);
 perform set_config('request.jwt.claim.sub',driver_b::text,true); perform public.goome_online(true);
 perform set_config('request.jwt.claim.sub',passenger::text,true);
 select value into signing_key from goome_private.settings where key='quote_secret';
 q:=jsonb_build_object('nonce',gen_random_uuid(),'pickup',jsonb_build_object('latitude',48.8566,'longitude',2.3522,'label','Test pickup'),'dropoff',jsonb_build_object('latitude',48.85,'longitude',2.37,'label','Test dropoff'),'rideClass','standard','distance',3000,'duration',600,'amount',1000,'expiresAt',floor(extract(epoch from clock_timestamp())*1000)::bigint+300000,'coordinates',jsonb_build_array(jsonb_build_array(2.3522,48.8566),jsonb_build_array(2.37,48.85)))::text;
 signature:=encode(extensions.hmac(convert_to(q,'UTF8'),convert_to(signing_key,'UTF8'),'sha256'),'hex');
 denied:=false; begin perform public.goome_request(q,'invalid'); exception when others then denied:=true; end;
 if not denied then raise exception 'FAILED: forged quote'; end if;
 ride_id:=public.goome_request(q,signature);
 denied:=false; begin perform public.goome_request(q,signature); exception when others then denied:=true; end;
 if not denied then raise exception 'FAILED: duplicate active passenger trip'; end if;
 denied:=false; begin perform public.goome_admin_driver(driver_b,false); exception when others then denied:=true; end;
 if not denied then raise exception 'FAILED: passenger admin access'; end if;
 perform set_config('request.jwt.claim.sub',driver_a::text,true);
 result:=public.goome_snapshot();
 if jsonb_array_length(result->'requests')<>1 then raise exception 'FAILED: nearby driver dispatch'; end if;
 perform public.goome_trip_action(ride_id,'accept',0);
 perform set_config('request.jwt.claim.sub',driver_b::text,true);
 denied:=false; begin perform public.goome_trip_action(ride_id,'accept',0); exception when others then denied:=true; end;
 if not denied then raise exception 'FAILED: double acceptance'; end if;
 denied:=false; begin perform public.goome_trip_action(ride_id,'arrive',1); exception when others then denied:=true; end;
 if not denied then raise exception 'FAILED: unrelated driver change'; end if;
 result:=public.goome_snapshot();
 if jsonb_array_length(result->'rides')<>0 then raise exception 'FAILED: cross-account trip visibility'; end if;
 perform set_config('request.jwt.claim.sub',driver_a::text,true);
 denied:=false; begin perform public.goome_trip_action(ride_id,'complete',1); exception when others then denied:=true; end;
 if not denied then raise exception 'FAILED: skipped trip stage'; end if;
 denied:=false; begin perform public.goome_trip_action(ride_id,'arrive',0); exception when others then denied:=true; end;
 if not denied then raise exception 'FAILED: stale trip update'; end if;
 perform public.goome_trip_action(ride_id,'arrive',1); perform public.goome_trip_action(ride_id,'start',2);
 perform set_config('request.jwt.claim.sub',passenger::text,true);
 denied:=false; begin perform public.goome_trip_action(ride_id,'cancel',3); exception when others then denied:=true; end;
 if not denied then raise exception 'FAILED: passenger ended in-progress trip'; end if;
 perform set_config('request.jwt.claim.sub',driver_a::text,true); perform public.goome_trip_action(ride_id,'complete',3);
 perform set_config('request.jwt.claim.sub',passenger::text,true); perform public.goome_rate(ride_id,5);
 denied:=false; begin perform public.goome_rate(ride_id,1); exception when others then denied:=true; end;
 if not denied then raise exception 'FAILED: duplicate rating'; end if;
 perform set_config('request.jwt.claim.sub',driver_a::text,true);
 select version into current_version from public.goome_rides where id=ride_id;
 perform public.goome_trip_action(ride_id,'confirm_cash',current_version);
 if not exists(select 1 from public.goome_rides where id=ride_id and status='completed' and payment_status='paid' and rating=5) then raise exception 'FAILED: completion/payment/rating'; end if;
 if has_function_privilege('anon','public.goome_snapshot()','EXECUTE') then raise exception 'FAILED: anonymous account access'; end if;
 if has_table_privilege('authenticated','goome_private.settings','SELECT') then raise exception 'FAILED: signing key readable'; end if;
 if has_table_privilege('authenticated','public.goome_profiles','UPDATE') then raise exception 'FAILED: direct profile role update'; end if;
 perform set_config('request.jwt.claim.sub',passenger::text,true);
 execute 'set local role authenticated';
 if (select count(*) from public.goome_profiles)<>1 then raise exception 'FAILED: profile RLS'; end if;
 if (select count(*) from public.goome_rides)<>1 then raise exception 'FAILED: ride RLS'; end if;
 result:=public.goome_snapshot();
 if result->'profile'->>'id'<>passenger::text then raise exception 'FAILED: authenticated RPC'; end if;
 execute 'reset role';
end $$;
rollback;
select 'PASS: registration, verified admin, driver approval, dispatch, signed quotes, double booking prevention, trip progression, cash confirmation, ratings, ownership, RLS and anonymous restrictions; test records rolled back' result;
